#!/usr/bin/env python
"""Turn a run_http --transcript file into docs/frontend-journeys.md: real answers, shortened, with link tokens hidden.

    venv/bin/python uat/transcript_to_md.py transcript.json > ../docs/frontend-journeys.md"""

import json
import re
import sys

INTRO = """# Lion Parts API: journeys with real answers

Generated by `backend/uat/transcript_to_md.py` from a recorded run of the UAT journeys (`backend/uat/journeys.py`) against an
isolated rehearsal of the staging: nginx, gunicorn, PostgreSQL, the demo supplier and the fake payment provider. Nothing is written
by hand, so every field shown exists. All people, phones and orders are test data.

To keep this readable, an object shows at most 12 keys and a list its first item; `api-handoff.md` section 5 lists every key.
Link tokens are replaced by `<token>`. `Accept-Language` is `en` unless a step says otherwise. Each unsafe request also sends
cookies and `X-CSRFToken`, as described in `api-handoff.md` section 1.
"""
TOKENS = re.compile(r"(token=|/[nq]/)[^&\s\"']+")
SECRET_KEYS = {"csrf_token", "token", "uid", "password", "new_password", "current_password"}


def short(value, key=None):
    if key in SECRET_KEYS:
        return "<hidden>"
    if isinstance(value, dict):
        out = {k: short(v, k) for k, v in list(value.items())[:12]}
        if len(value) > 12:
            out["…"] = f"+{len(value) - 12} more keys"
        return out
    if isinstance(value, list):
        return [short(item) for item in value[:1]] + ([f"… +{len(value) - 1} more"] if len(value) > 1 else [])
    if isinstance(value, str):
        value = TOKENS.sub(r"\1<token>", value)
        if value.lstrip().lower().startswith(("<!doctype", "<html")):
            return f"<html page, {len(value)} characters>"
        return value if len(value) <= 120 else value[:117] + "…"
    return value


def main(path):
    print(INTRO, end="")
    for number, journey in enumerate(json.load(open(path, encoding="utf8")), start=1):
        print(f"\n## {number}. {journey['journey'].replace('_', ' ').capitalize()}\n")
        if journey["doc"]:
            print(f"{journey['doc']}\n")
        print("```")
        for step in journey["steps"]:
            language = "" if step["language"] == "en" else f"  [Accept-Language: {step['language']}]"
            request = "" if step["request"] in (None, {}) else " " + json.dumps(short(step["request"]), ensure_ascii=False)
            print(f"{step['method']} {TOKENS.sub(r'\1<token>', step['path'])}{request}{language}")
            answer = short(step["response"])
            print(f"→ {step['status']} " + (json.dumps(answer, ensure_ascii=False) if answer not in ("", None) else "(empty)"))
            print()
        print("```")


if __name__ == "__main__":
    main(sys.argv[1])
